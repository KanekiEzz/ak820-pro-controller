"""Compare every packet builder against output captured from the original Rust code.

tests/golden_packets.txt was generated by compiling the original src/protocol.rs
and printing the result of each function (see README of the port).
"""

import os
import sys
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from ak820 import protocol as p  # noqa: E402

GOLDEN = os.path.join(os.path.dirname(__file__), "golden_packets.txt")


def hx(b):
    return bytes(b).hex()


def build_actual():
    out = {}
    out["start"] = hx(p.start_packet())
    out["finish"] = hx(p.finish_packet())
    out["mode_pre"] = hx(p.mode_preamble_packet())
    out["sleep_pre"] = hx(p.sleep_preamble_packet())
    out["image_pre"] = hx(p.image_preamble_packet())
    out["time_pre"] = hx(p.time_preamble_packet())
    out["save"] = hx(p.save_packet())

    dirs = [p.Direction.Left, p.Direction.Down, p.Direction.Up, p.Direction.Right]
    for idx in range(0x14):
        m = p.LightingMode.from_index(idx)
        out[f"name{idx}"] = m.label
        for k, d in enumerate(dirs):
            for rainbow in (False, True):
                out[f"mode{idx}_d{k}_r{int(rainbow)}"] = hx(
                    p.mode_data_packet(m, 0x12, 0x34, 0x56, rainbow, 9, 7, d))
        out[f"modeB{idx}"] = hx(
            p.mode_data_packet(m, 255, 0, 128, False, 3, 2, p.Direction.Left))
        out[f"dirs{idx}"] = ",".join(d.name for d in m.supported_directions())

    out["time1"] = hx(p.time_data_packet(2026, 10, 27, 10, 34, 56))
    out["time2"] = hx(p.time_data_packet(1999, 1, 2, 3, 4, 5))
    for s in p.SleepTime:
        out[f"sleep{int(s)}"] = hx(p.sleep_data_packet(s))
    for r, g, b in [(255, 0, 0), (0, 255, 0), (0, 0, 255), (255, 255, 255),
                    (255, 255, 0), (1, 2, 3), (128, 64, 32), (0, 0, 0)]:
        out[f"rgb565_{r}_{g}_{b}"] = hx(p.rgb565_encode(r, g, b))

    data = bytes(((i * 7 + i // 251) % 256) for i in range(p.LCD_DATA_SIZE))
    for i, c in enumerate(p.split_image_data(data)):
        out[f"chunk{i}"] = f"len={len(c)} head={hx(c[:4])} tail={hx(c[-4:])} sum={sum(c)}"

    for n in ["never", "off", "0", "1", "1m", "1min", "5", "5m", "5min", "30", "30m",
              "30min", "2", "abc", "NEVER", "1M"]:
        s = p.SleepTime.from_name(n)
        out[f"sleepname_{n}"] = str(int(s) if s is not None else -1)
    for n in ["left", "l", "down", "d", "up", "u", "right", "r", "LEFT", "x"]:
        d = p.Direction.from_name(n)
        out[f"dirname_{n}"] = str(int(d) if d is not None else -1)
    for n in ["off", "static", "single-on", "SINGLE-OFF", "breath", "shuttle", "nope",
              "single_on"]:
        m = p.LightingMode.from_name(n)
        out[f"modename_{n}"] = str(int(m) if m is not None else -1)
    return out


class GoldenTest(unittest.TestCase):
    def test_matches_rust_output(self):
        expected = {}
        with open(GOLDEN) as f:
            for line in f:
                line = line.rstrip("\n")
                if line:
                    key, _, value = line.partition(":")
                    expected[key] = value
        actual = build_actual()
        self.assertEqual(set(expected), set(actual))
        for key in expected:
            self.assertEqual(expected[key], actual[key], msg=key)


class QuirkTest(unittest.TestCase):
    def test_off_is_single_on_brightness_zero(self):
        self.assertEqual(
            p.resolve_lighting(p.LightingMode.Off, 5, 3),
            (p.LightingMode.SingleOn, 0, 0))

    def test_static_is_breath_speed_zero(self):
        self.assertEqual(
            p.resolve_lighting(p.LightingMode.Static, 4, 3),
            (p.LightingMode.Breath, 4, 0))

    def test_other_modes_unchanged(self):
        self.assertEqual(
            p.resolve_lighting(p.LightingMode.Spectrum, 4, 2),
            (p.LightingMode.Spectrum, 4, 2))

    def test_from_index_bounds(self):
        self.assertIsNone(p.LightingMode.from_index(0x14))
        self.assertIsNone(p.LightingMode.from_index(-1))
        self.assertEqual(p.LightingMode.from_index(0x13), p.LightingMode.Shuttle)


if __name__ == "__main__":
    unittest.main()
